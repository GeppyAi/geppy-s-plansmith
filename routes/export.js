const express = require('express');
const router = express.Router();
const { get, all } = require('../data/database');

// GET export spec for a project
router.get('/:projectId', async (req, res) => {
  try {
    const { format } = req.query; // 'markdown', 'json', 'preview'
    const project = await get(`SELECT * FROM projects WHERE project_id = ?`, [req.params.projectId]);
    if (!project) return res.status(404).json({ success: false, error: 'Project not found' });

    const states = await all(
      `SELECT * FROM project_states WHERE project_id = ? ORDER BY milestone_phase ASC, created_at ASC`,
      [req.params.projectId]
    );

    const linkedAssets = await all(
      `SELECT a.* FROM global_assets a
       JOIN project_asset_links l ON a.asset_id = l.asset_id
       WHERE l.project_id = ?`,
      [req.params.projectId]
    );

    const parsedAssets = linkedAssets.map(a => ({
      ...a,
      mutability_rules: JSON.parse(a.mutability_rules || '{}')
    }));

    const locked = states.filter(s => s.bucket === 'locked');
    const parkingLot = states.filter(s => s.bucket === 'parking_lot');
    const discarded = states.filter(s => s.bucket === 'discarded');

    // Group locked items by milestone phase
    const milestones = {};
    locked.forEach(item => {
      const p = item.milestone_phase || 1;
      if (!milestones[p]) milestones[p] = [];
      milestones[p].push(item);
    });

    if (format === 'json') {
      return res.json({
        success: true,
        export_date: new Date().toISOString(),
        project,
        assets: parsedAssets,
        states: {
          locked,
          parkingLot,
          discarded,
          milestones
        }
      });
    }

    // Build Tailored Markdown Specs
    let markdown = '';

    if (project.project_type === 'software') {
      markdown = `# SOFTWARE IMPLEMENTATION SPEC: ${project.title.toUpperCase()}\n\n`;
      markdown += `**Project Type**: Software Application\n`;
      markdown += `**GitHub Repository**: ${project.github_repo || 'Local Repository'}\n`;
      markdown += `**Branch Target**: ${project.github_branch || 'main'}\n`;
      markdown += `**Generated By**: PlanSmith Local Studio (${new Date().toLocaleDateString()})\n\n`;

      markdown += `## 1. Executive Summary & Purpose\n`;
      markdown += `${project.description || 'No detailed description provided.'}\n\n`;

      if (parsedAssets.length > 0) {
        markdown += `## 2. Global Source of Truth Assets & Governance Rules\n`;
        parsedAssets.forEach(ast => {
          markdown += `- **${ast.name}** (${ast.type.toUpperCase()}): \`${ast.file_path}\`\n`;
          if (ast.mutability_rules && Object.keys(ast.mutability_rules).length > 0) {
            markdown += `  - Governance Rules: \`${JSON.stringify(ast.mutability_rules)}\`\n`;
          }
        });
        markdown += `\n`;
      }

      markdown += `## 3. Locked Architecture & Tech Stack Decisions\n`;
      if (locked.length === 0) {
        markdown += `*No locked decisions recorded yet.*\n\n`;
      } else {
        locked.forEach(item => {
          markdown += `- **[${(item.category || 'ARCHITECTURE').toUpperCase()}]** ${item.content}\n`;
        });
        markdown += `\n`;
      }

      markdown += `## 4. Execution Milestones & Task Breakdown\n`;
      Object.keys(milestones).sort().forEach(phase => {
        markdown += `### Phase ${phase}\n`;
        milestones[phase].forEach(item => {
          markdown += `- [ ] ${item.content}\n`;
        });
        markdown += `\n`;
      });

      markdown += `## 5. Parking Lot (Future Roadmap)\n`;
      if (parkingLot.length === 0) {
        markdown += `*No pending ideas in parking lot.*\n\n`;
      } else {
        parkingLot.forEach(item => {
          markdown += `- ⏳ ${item.content}\n`;
        });
        markdown += `\n`;
      }

      markdown += `## 6. Discarded Options & Scope Guardrails\n`;
      if (discarded.length === 0) {
        markdown += `*No explicitly discarded items.*\n\n`;
      } else {
        discarded.forEach(item => {
          markdown += `- 🚫 ${item.content}\n`;
        });
        markdown += `\n`;
      }

      markdown += `---\n*Master Software Implementation Spec compiled by PlanSmith Local Suite.*`;

    } else if (project.project_type === 'physical') {
      markdown = `# PHYSICAL FABRICATION & ASSEMBLY SPEC: ${project.title.toUpperCase()}\n\n`;
      markdown += `**Project Type**: Physical Fabrication (3D Print / Laser Spec / CNC)\n`;
      markdown += `**Generated By**: PlanSmith Local Studio (${new Date().toLocaleDateString()})\n\n`;

      markdown += `## 1. Project Overview\n`;
      markdown += `${project.description || 'No detailed description provided.'}\n\n`;

      if (parsedAssets.length > 0) {
        markdown += `## 2. Reference Schematics & Asset Vault Links\n`;
        parsedAssets.forEach(ast => {
          markdown += `- **${ast.name}** (${ast.type.toUpperCase()}): \`${ast.file_path}\`\n`;
        });
        markdown += `\n`;
      }

      markdown += `## 3. Physical Parameters, Materials & Tolerances (Locked In)\n`;
      if (locked.length === 0) {
        markdown += `*No locked material or dimension specs recorded yet.*\n\n`;
      } else {
        locked.forEach(item => {
          markdown += `- 🛠️ **[${(item.category || 'FABRICATION').toUpperCase()}]** ${item.content}\n`;
        });
        markdown += `\n`;
      }

      markdown += `## 4. Fabrication Sequence & Assembly Steps\n`;
      Object.keys(milestones).sort().forEach(phase => {
        markdown += `### Step / Phase ${phase}\n`;
        milestones[phase].forEach(item => {
          markdown += `- [ ] ${item.content}\n`;
        });
        markdown += `\n`;
      });

      markdown += `## 5. Alternative Materials & Deferred Features (Parking Lot)\n`;
      parkingLot.forEach(item => {
        markdown += `- 💡 ${item.content}\n`;
      });
      markdown += `\n`;

      markdown += `## 6. Rejected Materials & Geometric Constraints\n`;
      discarded.forEach(item => {
        markdown += `- ❌ ${item.content}\n`;
      });
      markdown += `\n`;

    } else {
      // General / Event Spec
      markdown = `# GENERAL IMPLEMENTATION CHARTER: ${project.title.toUpperCase()}\n\n`;
      markdown += `**Project Type**: General / Event Scoping\n`;
      markdown += `**Generated By**: PlanSmith Local Studio (${new Date().toLocaleDateString()})\n\n`;

      markdown += `## 1. Description\n${project.description || 'N/A'}\n\n`;

      markdown += `## 2. Locked Decisions & Core Mandates\n`;
      locked.forEach(item => {
        markdown += `- ✅ ${item.content}\n`;
      });
      markdown += `\n`;

      markdown += `## 3. Milestone Timeline\n`;
      Object.keys(milestones).sort().forEach(phase => {
        markdown += `### Phase ${phase}\n`;
        milestones[phase].forEach(item => {
          markdown += `- [ ] ${item.content}\n`;
        });
        markdown += `\n`;
      });

      markdown += `## 4. Parking Lot (Deferred Backlog)\n`;
      parkingLot.forEach(item => {
        markdown += `- 📌 ${item.content}\n`;
      });
      markdown += `\n`;

      markdown += `## 5. Discarded Items & Non-Goals\n`;
      discarded.forEach(item => {
        markdown += `- 🚫 ${item.content}\n`;
      });
      markdown += `\n`;
    }

    res.setHeader('Content-Type', 'text/markdown');
    res.send(markdown);
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

module.exports = router;
